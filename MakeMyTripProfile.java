class MakeMyTripProfile {

    private int travelerId;
    private String travelerName;
    private String email;
    private String password;
    private String gender;
    private String dateOfBirth;
    private String city;
    private boolean isProfileActive;
    private String preferredDestination;

    public void setTravelerId(int travelerId) { 
		this.travelerId = travelerId; 
	}
    public int getTravelerId() { 
		return this.travelerId; 
	}

    public void setTravelerName(String travelerName) { 
		this.travelerName = travelerName; 
	}
    public String getTravelerName() { 
		return this.travelerName; 
	}

    public void setEmail(String email) { 
		this.email = email; 
	}
    public String getEmail() { 
		return this.email; 
	}

    public void setPassword(String password) { 
		this.password = password; 
	}
    public String getPassword() { 
		return this.password; 
	}

    public void setGender(String gender) { 
		this.gender = gender; 
	}
    public String getGender() { 
		return this.gender; 
	}

    public void setDateOfBirth(String dateOfBirth) { 
		this.dateOfBirth = dateOfBirth; 
	}
    public String getDateOfBirth() { 
		return this.dateOfBirth; 
	}

    public void setCity(String city) { 
		this.city = city; 
	}
    public String getCity() { 
		return this.city; 
	}

    public void setIsProfileActive(boolean isProfileActive) { 
		this.isProfileActive = isProfileActive; 
	}
    public boolean getIsProfileActive() { 
		return this.isProfileActive; 
	}

    public void setPreferredDestination(String preferredDestination) { 
		this.preferredDestination = preferredDestination; 
	}
    public String getPreferredDestination() { 
		return this.preferredDestination; 
	}
}
