class Blanket {
    String brand;
    String color;
    String material;
    double length;
    double width;
    double weight;
    Blanket() {}
    Blanket(String brand, String color, String material, double length, double width, double weight) {
        this.brand = brand;
        this.color = color;
        this.material = material;
        this.length = length;
        this.width = width;
        this.weight = weight;
    }
}