public class IndianArmy {  // Encapsulation

    private int soldierId;
    private String soldierName;
    private String rank;
    private String regiment;
    private String postingArea;
    private String enrolledOn;
    private String medals;

    public void setSoldierId(int soldierId) {
        this.soldierId = soldierId;
    }
    public int getSoldierId() {
        return this.soldierId;
    }

    public void setSoldierName(String soldierName) {
        this.soldierName = soldierName;
    }
    public String getSoldierName() {
        return this.soldierName;
    }

    public void setRank(String rank) {
        this.rank = rank;
    }
    public String getRank() {
        return this.rank;
    }

    public void setRegiment(String regiment) {
        this.regiment = regiment;
    }
    public String getRegiment() {
        return this.regiment;
    }

    public void setPostingArea(String postingArea) {
        this.postingArea = postingArea;
    }
    public String getPostingArea() {
        return this.postingArea;
    }

    public void setEnrolledOn(String enrolledOn) {
        this.enrolledOn = enrolledOn;
    }
    public String getEnrolledOn() {
        return this.enrolledOn;
    }

    public void setMedals(String medals) {
        this.medals = medals;
    }
    public String getMedals() {
        return this.medals;
    }

}
